/* ---------- Render cards ---------- */
const grid = $('#workGrid');
const playIcon = '<svg viewBox="0 0 24 24"><path d="M8 5v14l11-7z"/></svg>';
let cardObserver; // declared up here so observeCards() can use it on first render

function cardHTML(p) {
  const cat = CATEGORIES[p.cat] || CATEGORIES.all;
  const idx = (p._i === undefined) ? '' : p._i;
  const thumb = p.thumb ? encode(p.thumb) : '';
  const clip  = p.web ? encode(p.web) : encode(p.file);
  const bg = thumb
    ? `background-image:url('${thumb}');background-size:cover;background-position:center`
    : `background:linear-gradient(135deg,var(--c1),var(--c2))`;
  return `
    <article class="work-card" data-cat="${p.cat}" data-index="${idx}"
             style="--c1:${cat.c1};--c2:${cat.c2}">
      <div class="poster" style="${bg}">
        <video class="clip" muted loop playsinline preload="none"
               poster="${thumb}" data-src="${clip}" aria-label="${p.title}"></video>
        <span class="poster-tag">${cat.label}</span>
        ${p.dur ? `<span class="poster-dur">${p.dur}</span>` : ''}
        <span class="poster-icon">${playIcon}</span>
      </div>
    </article>`;
}

function renderCards(list) {
  grid.innerHTML = list.map(cardHTML).join('');
  observeCards();
}

