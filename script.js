/* ---------- Lightbox player ---------- */
const lightbox = $('#lightbox');
const lbVideo  = $('#lightboxVideo');
const lbTitle  = $('#lbTitle');
const lbCat    = $('#lbCat');
const lbClose  = $('#lightboxClose');

grid.addEventListener('click', e => {
  const card = e.target.closest('.work-card');
  if (!card) return;
  const index = Number(card.dataset.index);
  const p = PROJECTS[index];
  if (!p) return;
  const cat = CATEGORIES[p.cat] || CATEGORIES.all;
  lbTitle.textContent = p.title;
  lbCat.textContent = cat.label;
  // Play the web-friendly H.264 clip (falls back to the original if missing).
  lbVideo.src = p.web ? encode(p.web) : encode(p.file);
  // Pause the muted inline preview so audio doesn't double up.
  const inline = card.querySelector('video.clip');
  if (inline) inline.pause();
  lightbox.classList.add('open');
  lightbox.setAttribute('aria-hidden', 'false');
  document.body.style.overflow = 'hidden';
  lbVideo.play().catch(() => {});
});

function closeLightbox() {
  lightbox.classList.remove('open');
  lightbox.setAttribute('aria-hidden', 'true');
  document.body.style.overflow = '';
  lbVideo.pause();
  lbVideo.removeAttribute('src');
  lbVideo.load();
}
lbClose.addEventListener('click', closeLightbox);
lightbox.addEventListener('click', e => { if (e.target === lightbox) closeLightbox(); });
document.addEventListener('keydown', e => { if (e.key === 'Escape' && lightbox.classList.contains('open')) closeLightbox(); });

/* ---------- Scroll reveal + lazy autoplay for cards ---------- */
function observeCards() {
  const cards = document.querySelectorAll('.work-card');
  if (!cards.length) return;

  if (!('IntersectionObserver' in window)) {
    cards.forEach(c => c.classList.add('in'));
    return;
  }
  if (!cardObserver) {
    cardObserver = new IntersectionObserver((entries, obs) => {
      entries.forEach(entry => {
        if (!entry.isIntersecting) return;
        const card = entry.target;
        card.classList.add('in');
        // Lazy-load + autoplay the muted inline preview once visible.
        const v = card.querySelector('video.clip');
        if (v && v.dataset.src && !v.src) {
          v.addEventListener('playing', () => card.querySelector('.poster')?.classList.add('playing'), { once: true });
          v.src = v.dataset.src;
          v.addEventListener('loadeddata', () => v.play().catch(() => {}), { once: true });
          v.load();
        }
        obs.unobserve(card);
      });
    }, { threshold: 0.25 });
  }
  cards.forEach(c => cardObserver.observe(c));
}

/* ---------- Nav smooth scroll + active state ---------- */
document.querySelectorAll('a[href^="#"]').forEach(link => {
  link.addEventListener('click', event => {
    const id = link.getAttribute('href');
    if (id.length < 2) return;
    const target = document.querySelector(id);
    if (target) {
      event.preventDefault();
      target.scrollIntoView({ behavior: 'smooth', block: 'start' });
    }
  });
});

/* ---------- Animated stat counters ---------- */
const statNums = document.querySelectorAll('.stat dd[data-count]');
if ('IntersectionObserver' in window && statNums.length) {
  const statObs = new IntersectionObserver((entries, obs) => {
    entries.forEach(entry => {
      if (!entry.isIntersecting) return;
      const el = entry.target;
      const end = Number(el.dataset.count);
      const dur = 1200; const start = performance.now();
      // Keep the trailing suffix (<i>+</i>) and only swap the number text node.
      const suffix = el.querySelector('i');
      const suffixHTML = suffix ? suffix.outerHTML : '';
      function tick(now) {
        const prog = Math.min((now - start) / dur, 1);
        const val = Math.floor(prog * end);
        el.innerHTML = val + suffixHTML;
        if (prog < 1) requestAnimationFrame(tick);
        else el.innerHTML = end + suffixHTML;
      }
      requestAnimationFrame(tick);
      obs.unobserve(el);
    });
  }, { threshold: 0.5 });
  statNums.forEach(el => statObs.observe(el));
}

/* ---------- Active nav highlight while scrolling ---------- */
const navLinks = document.querySelectorAll('.site-header nav a[href^="#"]');
const sections = document.querySelectorAll('main section[id]');
if ('IntersectionObserver' in window && sections.length) {
  const navObs = new IntersectionObserver(entries => {
    entries.forEach(entry => {
      if (entry.isIntersecting) {
        navLinks.forEach(l => l.classList.remove('active'));
        const active = document.querySelector('.site-header nav a[href="#' + entry.target.id + '"]');
        if (active) active.classList.add('active');
      }
    });
  }, { threshold: 0.35 });
  sections.forEach(sec => navObs.observe(sec));
}

